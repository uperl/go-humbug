#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_LICENSES from the modules compiled into cmd/humbug.

    make licenses

Reads each dependency's license (and NOTICE) file from the Go module cache, so run it after
`go mod download`. Covers what ships in the binary, not test-only dependencies. Review the diff:
a dependency with a license this script does not recognize stops the run.

Documents compiled into the binary from outside Go modules are listed in BUNDLED, each with its
upstream license file kept in the repository.
"""
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LICENSE_FILES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "COPYING")
NOTICE_FILES = ("NOTICE", "NOTICE.md", "NOTICE.txt")

# (name, source, license file): documents embedded with //go:embed rather than from a module.
BUNDLED = [
    ("OpenAPI Specification schemas", "spec.openapis.org/oas/3.1", "internal/offline/schemas-LICENSE"),
]


def sh(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def kind(text):
    if text.lstrip().startswith(("MIT License", "The MIT License")):
        return "MIT"
    if "Apache License" in text[:200] and "Version 2.0" in text[:300]:
        return "Apache-2.0"
    if "Redistributions of source code must retain" in text and "Neither the name" in text:
        return "BSD-3-Clause"
    return None


def first(d, names):
    for n in names:
        p = Path(d) / n
        if p.is_file():
            return p.read_text()
    return None


def main():
    out = sh("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}", "./cmd/humbug")
    mods = sorted({tuple(line.split(" ", 2)) for line in out.splitlines() if line.strip()})
    entries = []
    for path, version, d in mods:
        text = first(d, LICENSE_FILES)
        if text is None:
            sys.exit("no license file for %s %s" % (path, version))
        k = kind(text)
        if k is None:
            sys.exit("unrecognized license for %s %s: review it by hand" % (path, version))
        entries.append((path, version, k, text.strip("\n"), first(d, NOTICE_FILES)))
    bundled = []
    for name, source, f in BUNDLED:
        text = (ROOT / f).read_text()
        k = kind(text)
        if k is None:
            sys.exit("unrecognized license for %s (%s): review it by hand" % (name, f))
        bundled.append((name, source, k, text.strip("\n")))
    goroot = sh("go", "env", "GOROOT").strip()
    goversion = sh("go", "env", "GOVERSION").strip()
    std = (Path(goroot) / "LICENSE").read_text().strip("\n")

    w = []
    w.append("""THIRD PARTY LICENSES

Humbug itself is licensed under the MIT License (see LICENSE). The binary built from cmd/humbug
includes the Go standard library, the modules below and the bundled documents below them, each under
its own license, reproduced here as required. Test-only dependencies are not part of the binary and
are not listed.

This file is generated by `make licenses` (scripts/third_party_licenses.py) from the license files
in the dependencies' source and, for bundled documents, the upstream license files kept beside them.
Do not edit it by hand.

Summary
-------
""")
    rows = [("Go standard library", goversion, "BSD-3-Clause")] + [(p, v, k) for p, v, k, _, _ in entries]
    rows += [(n, src, k) for n, src, k, _ in bundled]
    width = max(len(r[0]) for r in rows)
    for name, version, k in rows:
        w.append("  %-*s  %-44s  %s\n" % (width, name, version, k))
    sep = "\n" + "=" * 78 + "\n"
    w.append(sep + "Go standard library (%s) - BSD-3-Clause\n" % goversion + "=" * 78 + "\n\n" + std + "\n")
    for path, version, k, text, notice in entries:
        w.append(sep + "%s %s - %s\n" % (path, version, k) + "=" * 78 + "\n\n" + text + "\n")
        if notice:
            w.append("\n--- NOTICE (%s) ---\n\n%s\n" % (path, notice.strip("\n")))
    for name, source, k, text in bundled:
        w.append(sep + "%s (%s) - %s\n" % (name, source, k) + "=" * 78 + "\n\n" + text + "\n")
    (ROOT / "THIRD_PARTY_LICENSES").write_text("".join(w))
    print("wrote THIRD_PARTY_LICENSES (%d modules, %d bundled)" % (len(entries), len(bundled)))


if __name__ == "__main__":
    main()
